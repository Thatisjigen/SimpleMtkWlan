#!/usr/bin/env python3
"""Write include/FwMT7920.inc, the MT7920 firmware pair, from linux-firmware.

MediaTek lets these files be redistributed for devices with its chipsets, but
not in a form that would put them under the GPL (LICENSES/LICENCE.mediatek in
linux-firmware), so they stay out of this repository and each build gets them
from the source, pinned by commit and SHA-256.

  gen-mt7920-fw.py                 the pair Linux loads today (build 20260224)
  gen-mt7920-fw.py --set 2024      the first pair, closest to the MT7921 and
                                   MT7922 images in FwBinary.cpp (2023)
  gen-mt7920-fw.py --from DIR      read the two files from DIR, same checks
"""
import argparse
import hashlib
import struct
import sys
import urllib.request
from pathlib import Path

BASE = 'https://git.kernel.org/pub/scm/linux/kernel/git/firmware/linux-firmware.git/plain/mediatek/'
PATCH = 'WIFI_MT7961_patch_mcu_1a_2_hdr.bin'
RAM = 'WIFI_RAM_CODE_MT7961_1a.bin'
SETS = {
    '2026': ('87414f9ba8f875cb733281652474bccf93313e2f',
             'a766c4e39815e554c80ce5b1596095ff283a60db93356679fecd6494f71cee23',
             '3edec74ffe341b917e7fa4ddb2b68851411f2416555f10619a5900fa4b141e6c'),
    '2024': ('3ce84a8dbf4a418cc982503596e481a1be84eab1', 'ea5d34f745eb5d68f8873bb33470b19862bcb020510a1a5eba9d98e515c48043', 'cf804d47846d0407127b48c014a872f9a6427db6cc332e31e7699de11fae5130'),
}
PATCH_HDR, PATCH_SEC, FW_TRAILER, FW_REGION = 96, 64, 36, 40
PATCH_SEC_TYPE_MASK, PATCH_SEC_TYPE_INFO = 0xffff, 0x2


def check_patch(b):
    """The checks of mwx_load_firmware(), on the patch image."""
    regions = struct.unpack('>I', b[44:48])[0]
    if len(b) < PATCH_HDR + regions * PATCH_SEC:
        raise ValueError('patch: short header')
    for i in range(regions):
        off = PATCH_HDR + i * PATCH_SEC
        typ, data = struct.unpack('>II', b[off:off + 8])
        length = struct.unpack('>I', b[off + 16:off + 20])[0]
        if typ & PATCH_SEC_TYPE_MASK != PATCH_SEC_TYPE_INFO:
            raise ValueError('patch: region %d has type 0x%x' % (i, typ))
        if data + length > len(b):
            raise ValueError('patch: region %d past the end' % i)
    return 'patch build %s regions %d' % (b[:15].decode(), regions)


def check_ram(b):
    """The checks of mwx_load_firmware(), on the WM image."""
    t = b[-FW_TRAILER:]
    regions = t[2]
    table = len(b) - FW_TRAILER - regions * FW_REGION
    if table < 0:
        raise ValueError('wm: short header')
    used = 0
    for i in range(regions):
        used += struct.unpack('<I', b[table + i * FW_REGION + 20:table + i * FW_REGION + 24])[0]
    if used > table:
        raise ValueError('wm: regions past the payload')
    return 'wm %s build %s regions %d' % (t[7:17].decode(), t[17:31].decode(), regions)


def emit(name, b):
    lines = ['unsigned char %s[] = {' % name]
    for i in range(0, len(b), 12):
        lines.append('  ' + ', '.join('0x%02x' % x for x in b[i:i + 12]) + ',')
    lines += ['};', 'unsigned int %s_len = %d;' % (name, len(b)), '']
    return '\n'.join(lines)


def get(name, commit, src):
    if src:
        return (Path(src) / name).read_bytes()
    url = '%s%s?id=%s' % (BASE, name, commit)
    with urllib.request.urlopen(url, timeout=120) as r:
        return r.read()


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--set', default='2026', choices=sorted(SETS))
    ap.add_argument('--from', dest='src')
    args = ap.parse_args()
    commit, patch_sha, ram_sha = SETS[args.set]
    patch, ram = get(PATCH, commit, args.src), get(RAM, commit, args.src)
    for name, data, want in ((PATCH, patch, patch_sha), (RAM, ram, ram_sha)):
        have = hashlib.sha256(data).hexdigest()
        if have != want:
            sys.exit('%s: SHA-256 %s, expected %s' % (name, have, want))
    notes = [check_patch(patch), check_ram(ram)]
    out = Path(__file__).resolve().parents[1] / 'include/FwMT7920.inc'
    out.write_text('/* Generated by tools/gen-mt7920-fw.py: linux-firmware %s; %s */\n%s%s' % (
        commit, '; '.join(notes), emit('mwx_mt7961_patch_mcu_1a_2_hdr', patch),
        emit('mwx_mt7961_ram_code_1a', ram)))
    print('%s: linux-firmware %s; %s' % (out.name, commit[:12], '; '.join(notes)))


if __name__ == '__main__':
    main()
